function ir_desc(string $title, array $why, array $route): string
{
    $whyHtml = '';
    foreach ($why as $item) {
        $whyHtml .= '<li>'.e($item).'</li>';
    }
    $routeHtml = '';
    foreach ($route as $item) {
        $routeHtml .= '<li>'.e($item).'</li>';
    }

    return '<p><strong>'.e($title).'</strong></p>'
        .'<p><strong>Почему именно это направление:</strong></p>'
        .'<ul>'.$whyHtml.'</ul>'
        .'<p><strong>Что включить в ваш маршрут:</strong></p>'
        .'<ul>'.$routeHtml.'</ul>';
}

