    $rows = CategoryDescription::query()->where('category_id', $categoryId)->get();
    if ($rows->isEmpty()) {
        echo "MISS category_id={$categoryId}\n";
        $missing++;
        continue;
    }

    foreach ($rows as $row) {
        $row->description = $html;
        $row->save();
        $updated++;
        echo "OK id={$categoryId} lang={$row->language_id} name={$row->name}\n";
    }
}

